// public/sw-push.js
// Gestionnaire Web Push pour la PWA Biblio Collection.

self.addEventListener('push', (event) => {
  let payload = {
    title: 'Biblio Collection — Nouveautés',
    body: 'De nouveaux tomes sont disponibles dans vos séries.',
    url: '/releases'
  };
  if (event.data) {
    try {
      payload = { ...payload, ...event.data.json() };
    } catch {
      payload.body = event.data.text() || payload.body;
    }
  }
  event.waitUntil(
    self.registration.showNotification(payload.title, {
      body: payload.body,
      icon: '/192.png',
      badge: '/192.png',
      data: { url: payload.url || '/releases' }
    })
  );
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const targetUrl = (event.notification.data && event.notification.data.url) || '/releases';
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((clientList) => {
      for (const client of clientList) {
        if ('focus' in client) {
          client.focus();
          if ('navigate' in client) client.navigate(targetUrl);
          return;
        }
      }
      if (self.clients.openWindow) {
        return self.clients.openWindow(targetUrl);
      }
    })
  );
});
